const DICTS: Record<Lang, Partial<Record<TKey, string>>> = { ku, ar, en };

/**
 * Standalone translator for code that must render without a working provider —
 * an error boundary, for instance, which by definition cannot trust the tree
 * above it. Returns the chosen language's text, falling back to English.
 */
export function translateIn(lang: Lang): (k: TKey) => string {
  const dict = DICTS[lang] ?? en;
  return (k: TKey) => dict[k] ?? en[k] ?? String(k);
}
export const LANGS: Array<{ code: Lang; label: string; dir: 'rtl' | 'ltr' }> = [
  { code: 'ku', label: 'کوردی', dir: 'rtl' },
  { code: 'ar', label: 'العربية', dir: 'rtl' },
  { code: 'en', label: 'English', dir: 'ltr' },
];
type Ctx = {
  lang: Lang;
  dir: 'rtl' | 'ltr';
  setLang: (l: Lang) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
};
const I18nContext = createContext<Ctx | null>(null);
function detectLang(): Lang {
  const saved = localStorage.getItem('parez.lang');
  if (saved === 'ku' || saved === 'ar' || saved === 'en') return saved;
  return 'ku';
}
export function I18nProvider({ children, initial }: { children: ReactNode; initial?: Lang }) {
  const [lang, setLangState] = useState<Lang>(initial ?? detectLang());
  useEffect(() => {
    const dir = LANGS.find((l) => l.code === lang)?.dir ?? 'rtl';
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang]);
  const value = useMemo<Ctx>(() => {
    const dir = LANGS.find((l) => l.code === lang)?.dir ?? 'rtl';
    const t: Ctx['t'] = (key, vars) => {
      let text = DICTS[lang][key] ?? ku[key] ?? String(key);
      if (vars) {
        for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{{${k}}}`, String(v));
      }
      return text;
    };
    const setLang = (l: Lang) => {
      localStorage.setItem('parez.lang', l);
      setLangState(l);
    };
    return { lang, dir, setLang, t };
  }, [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n outside provider');
  return ctx;
}
